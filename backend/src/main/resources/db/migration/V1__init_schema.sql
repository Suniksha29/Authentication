-- Flyway V1: Initial Schema for Meridian Enterprise Portal
-- Supports PostgreSQL and H2 (PostgreSQL compatibility mode)

CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    code VARCHAR(20) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    job_title VARCHAR(150) NOT NULL,
    role VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL,
    department_id BIGINT NOT NULL,
    manager_id BIGINT,
    google_sub VARCHAR(255),
    avatar_url VARCHAR(500),
    phone VARCHAR(50),
    hire_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_employees_dept FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_employees_mgr FOREIGN KEY (manager_id) REFERENCES employees (id)
);

CREATE INDEX idx_employees_email ON employees(email);
CREATE INDEX idx_employees_status ON employees(status);
CREATE INDEX idx_employees_dept ON employees(department_id);
CREATE INDEX idx_employees_role ON employees(role);
CREATE INDEX idx_employees_mgr ON employees(manager_id);

CREATE TABLE leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    leave_type VARCHAR(50) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    days_count INTEGER NOT NULL,
    reason TEXT NOT NULL,
    status VARCHAR(50) NOT NULL,
    reviewer_id BIGINT,
    review_notes TEXT,
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_leave_employee FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT fk_leave_reviewer FOREIGN KEY (reviewer_id) REFERENCES employees (id)
);

CREATE INDEX idx_leave_employee ON leave_requests(employee_id);
CREATE INDEX idx_leave_status ON leave_requests(status);
CREATE INDEX idx_leave_start_date ON leave_requests(start_date);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(50) NOT NULL,
    actor_email VARCHAR(255) NOT NULL,
    actor_role VARCHAR(50),
    target_resource VARCHAR(255),
    ip_address VARCHAR(100),
    user_agent VARCHAR(500),
    details TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_action ON audit_logs(action);
CREATE INDEX idx_audit_actor ON audit_logs(actor_email);
CREATE INDEX idx_audit_created ON audit_logs(created_at);

CREATE TABLE auth_flow_traces (
    id VARCHAR(100) PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    outcome VARCHAR(50) NOT NULL,
    steps_json TEXT NOT NULL,
    claims_json TEXT NOT NULL,
    ip_address VARCHAR(100),
    user_agent VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_auth_flow_email ON auth_flow_traces(email);
CREATE INDEX idx_auth_flow_created ON auth_flow_traces(created_at);

