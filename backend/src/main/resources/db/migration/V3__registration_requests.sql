-- Flyway V3: Add Registration Requests Table and Password Hash Column to Employees

CREATE TABLE registration_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(200) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255),
    status VARCHAR(50) NOT NULL,
    verification_token VARCHAR(100) NOT NULL UNIQUE,
    approval_token VARCHAR(100) NOT NULL UNIQUE,
    verified_at TIMESTAMP,
    approved_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_reg_email ON registration_requests(email);
CREATE INDEX idx_reg_verif_token ON registration_requests(verification_token);
CREATE INDEX idx_reg_appr_token ON registration_requests(approval_token);
CREATE INDEX idx_reg_status ON registration_requests(status);

ALTER TABLE employees ADD COLUMN password_hash VARCHAR(255);

